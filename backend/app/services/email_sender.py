"""Sends the post-meeting summary email over SMTP."""

from __future__ import annotations

import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText

from .. import config


class EmailError(RuntimeError):
    pass


def _escape(s: str) -> str:
    return str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _render_html(session_meet_url: str, summary: dict, duration_label: str) -> str:
    body = _escape(summary.get("summary", "")).replace("\n", "<br>")
    return f"""
    <div style="font-family: -apple-system, Segoe UI, Roboto, sans-serif; max-width:640px; margin:0 auto; color:#1a1a1a;">
      <h2 style="margin-bottom:4px;">Proxy AI meeting summary</h2>
      <p style="color:#555; margin-top:0;">{_escape(session_meet_url)} &middot; {_escape(duration_label)}</p>
      <div style="font-size:14px; line-height:1.6;">{body}</div>
      <p style="color:#999; font-size:12px; margin-top:24px;">Generated by Proxy AI using {_escape(summary.get('model', 'groq'))}.</p>
    </div>
    """


def send_summary_email(*, to_email: str, meet_url: str, summary: dict, duration_label: str) -> None:
    if not config.SMTP_HOST or not config.SMTP_USERNAME or not config.SMTP_PASSWORD:
        raise EmailError("SMTP_HOST/SMTP_USERNAME/SMTP_PASSWORD are not fully configured")
    if not to_email:
        raise EmailError("No recipient email configured")

    message = MIMEMultipart("alternative")
    message["Subject"] = f"Proxy AI meeting summary: {meet_url}"[:120]
    message["From"] = config.SMTP_FROM_EMAIL
    message["To"] = to_email
    message.attach(MIMEText(_render_html(meet_url, summary, duration_label), "html"))

    try:
        with smtplib.SMTP(config.SMTP_HOST, config.SMTP_PORT, timeout=30) as server:
            if config.SMTP_USE_TLS:
                server.starttls()
            server.login(config.SMTP_USERNAME, config.SMTP_PASSWORD)
            server.sendmail(config.SMTP_FROM_EMAIL, [to_email], message.as_string())
    except smtplib.SMTPException as exc:
        raise EmailError(str(exc)) from exc
